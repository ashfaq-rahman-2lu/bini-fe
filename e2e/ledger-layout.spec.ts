import { execFileSync } from 'node:child_process'
import path from 'node:path'
import { test, expect } from '@playwright/test'

const backend = path.resolve(process.env.BACKEND_DIR || '../backend')
const env = { ...process.env, DATABASE_URL: process.env.TEST_DATABASE_URL || 'postgresql+psycopg://bini:bini_local_only@127.0.0.1:55433/bini_test', PYTHONPATH: backend + path.delimiter + path.join(backend, 'tests'), PYTHONDONTWRITEBYTECODE: '1' }

test('ledger filters, chips, totals and aligned controls work on desktop and mobile', async ({ page }, testInfo) => {
  execFileSync(path.join(backend, '.venv/bin/python'), ['-c', `
from conftest import engine
from sqlalchemy import text
from datetime import date, timedelta
from test_reconciliation import seed_transfers
with engine.begin() as c:
    c.execute(text('TRUNCATE investment_institutions, source_links, statement_rows, transactions, statements, accounts CASCADE'))
seed_transfers([((date(2025, 9, 1)+timedelta(days=n)).isoformat(), 'credit' if n % 2 else 'debit', str(100+n), ('EFT INFLOW ' if n % 2 else 'Other Bank Transfer SKB-BEFTN ')+'Synthetic transfer '+str(n)) for n in range(55)])
`], { env })
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message))
  await page.setViewportSize({ width: 1305, height: 800 })
  await page.goto('/transactions')
  await expect(page.getByRole('region', { name: 'Filtered totals' })).toContainText('55')
  await expect(page.locator('.ledger-table tbody tr')).toHaveCount(50)
  await expect(page.locator('.ledger-direction.debit').first()).toHaveText('Debit')
  await expect(page.locator('.ledger-table .amount.credit').first()).toContainText('+')
  expect(await page.getByLabel('Type', { exact: true }).evaluate(e => parseInt(getComputedStyle(e).paddingRight))).toBeGreaterThanOrEqual(30)
  const controls = await page.locator('.ledger-filters input, .ledger-filters select, .ledger-filters > button').evaluateAll(elements => elements.map(e => e.getBoundingClientRect().bottom))
  expect(Math.max(...controls) - Math.min(...controls)).toBeLessThan(2)
  await page.screenshot({ path: testInfo.outputPath('ledger-desktop.png'), fullPage: true })
  await page.getByRole('button', { name: 'Next page' }).click()
  await expect(page.locator('.ledger-table tbody tr')).toHaveCount(5)
  await page.getByLabel('Description', { exact: true }).fill('Synthetic')
  await page.getByLabel('Type', { exact: true }).selectOption('credit')
  await page.getByRole('button', { name: 'Apply filters' }).click()
  await expect(page.locator('.ledger-table tbody tr')).toHaveCount(27)
  await expect(page.getByRole('region', { name: 'Filtered totals' })).toContainText('3,429.00')
  await page.getByLabel('Sort transactions').selectOption('amount_asc')
  await page.getByRole('button', { name: 'Remove type filter' }).click()
  await expect(page).toHaveURL(/sort=amount_asc/)
  await expect(page).not.toHaveURL(/direction=/)
  await page.reload()
  await expect(page.getByLabel('Description', { exact: true })).toHaveValue('Synthetic')
  await page.getByRole('button', { name: 'Clear filters', exact: true }).click()
  await expect(page).toHaveURL(/sort=amount_asc/)
  await expect(page.getByLabel('Applied filters')).toHaveCount(0)
  await page.getByLabel('From date').fill('2025-10-20')
  await page.getByLabel('To date').fill('2025-10-01')
  await page.getByRole('button', { name: 'Apply filters' }).click()
  await expect(page.getByRole('alert')).toContainText('From date must not be after to date.')
  await page.getByLabel('From date').fill('2025-10-01')
  await page.getByLabel('To date').fill('2025-10-20')
  await page.getByRole('button', { name: 'Apply filters' }).click()
  await expect(page.getByRole('alert')).toHaveCount(0)
  await expect(page.locator('.ledger-table tbody tr')).toHaveCount(20)
  await page.getByRole('button', { name: 'SKB', exact: true }).click()
  await expect(page.locator('.ledger-table tbody tr')).toHaveCount(10)
  await expect(page.getByLabel('Description', { exact: true })).toHaveValue('skb')
  await expect(page.getByRole('button', { name: 'SKB', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(page).toHaveURL(/from_date=2025-10-01/)
  await expect(page).toHaveURL(/sort=amount_asc/)
  await expect(page.getByRole('region', { name: 'Filtered totals' })).toContainText('1,390.00')
  await page.reload()
  await expect(page.getByRole('button', { name: 'SKB', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'EFT inflow', exact: true }).click()
  await expect(page.getByLabel('Description', { exact: true })).toHaveValue('eft inflow')
  await expect(page.locator('.ledger-table tbody tr')).toHaveCount(10)
  await expect(page.getByRole('region', { name: 'Filtered totals' })).toContainText('1,400.00')
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  const amount = await page.locator('.ledger-amount').first().boundingBox()
  expect(amount!.x + amount!.width).toBeLessThanOrEqual(390)
  await page.locator('.ledger-table .description-button').first().click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.getByRole('button', { name: 'Close details' }).click()
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: testInfo.outputPath('ledger-mobile.png'), fullPage: true })
  await page.goto('/investments')
  await page.setViewportSize({ width: 1305, height: 800 })
  await expect(page.getByRole('combobox', { name: 'Project', exact: true })).toBeVisible()
  const buttons = await page.locator('.page-header .reconciliation-actions a').evaluateAll(elements => elements.map(e => ({ top: e.getBoundingClientRect().top, height: e.getBoundingClientRect().height })))
  expect(Math.abs(buttons[0].top - buttons[1].top)).toBeLessThan(1)
  expect(Math.abs(buttons[0].height - buttons[1].height)).toBeLessThan(1)
  const bar = await page.locator('.investment-filter-bar select, .investment-filter-bar > button').evaluateAll(elements => elements.map(e => ({ top: e.getBoundingClientRect().top, height: e.getBoundingClientRect().height })))
  expect(Math.abs(bar[0].top - bar[1].top)).toBeLessThan(1)
  expect(Math.abs(bar[0].height - bar[1].height)).toBeLessThan(1)
  expect(await page.getByRole('combobox', { name: 'Project', exact: true }).evaluate(e => parseInt(getComputedStyle(e).paddingRight))).toBeGreaterThanOrEqual(30)
  await page.screenshot({ path: testInfo.outputPath('investment-controls.png'), fullPage: true })
  await page.setViewportSize({ width: 740, height: 695 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  expect(errors).toEqual([])
})
