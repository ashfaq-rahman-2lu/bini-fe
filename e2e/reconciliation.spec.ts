test('reconciliation explains which waiting movements resolved or now need review', async ({ page }, testInfo) => {
  await importReport(page, 'reinvestment_csv(True)')
  const workspace = await (await authenticatedApi(page).get('/api/investments')).json()
  const events = workspace.events.slice(0, 3)
  const institution = workspace.institutions[0]
  const issue = (index: number, kind: string) => ({ id: `case-${index}`, key: `${kind}:${events[index].id}`, kind, event_id: events[index].id, institution_id: institution.id, message: 'Synthetic reconciliation dependency.' })
  const resolved = (index: number, kind: string) => ({ id: `resolved-${index}`, kind, event_id: events[index].id, institution_id: institution.id, amount: events[index].amount, status: 'resolved', connection_count: 1, provenance: 'automatic', explanation: 'Unique source match.', resolved_at: '2026-11-09T05:00:00Z', resolutions: [] })
  const common = { revision: 'synthetic', institutions: [], differences: [], difference_total: '0.00', pending_allocations: [], pending_bank_links: [] }
  const before = { ...common, issues: [issue(0, 'bank_match'), issue(1, 'dependent_wallet'), issue(2, 'dependent_wallet')], resolved: [] }
  const after = { ...common, issues: [issue(1, 'wallet_match')], resolved: [resolved(0, 'bank_match'), resolved(2, 'wallet_match')], saved: { allocations: 1, bank_links: 1, associations: 0 } }
  let updated = false
  await page.route('**/api/investments/reconciliation', route => route.fulfill({ json: updated ? after : before }))
  await page.route('**/api/jobs', route => {
    if (route.request().postDataJSON()?.kind !== 'reconcile') return route.continue()
    updated = true
    return route.fulfill({ status: 202, json: { id: 'mock-reconciliation', kind: 'reconcile', status: 'queued' } })
  })
  await page.route('**/api/jobs/mock-reconciliation', route => route.fulfill({ json: { id: 'mock-reconciliation', kind: 'reconcile', status: 'succeeded', result: after } }))
  await page.getByRole('link', { name: 'Money reconciliation', exact: true }).click()
  await expect(page.getByLabel('Reconciliation counts', { exact: true })).toContainText('Waiting2')
  await page.getByRole('button', { name: 'Reconcile now', exact: true }).click()
  const changes = page.getByRole('region', { name: 'Latest reconciliation changes', exact: true })
  await expect(changes).toContainText('3 movement status updates: 2 resolved, 1 to review')
  await expect(changes.locator('li')).toHaveCount(3)
  await expect(changes).toContainText('Wallet: Waiting → Resolved')
  await expect(changes).toContainText('Wallet: Waiting → To review')
  await expect(changes).toContainText('Bank: To review → Resolved')
  await changes.getByRole('button', { name: 'Payment details', exact: true }).first().click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.getByRole('button', { name: 'Close investment details', exact: true }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  await changes.scrollIntoViewIfNeeded()
  await page.screenshot({ path: testInfo.outputPath('reconciliation-changes-phone.png') })
  await page.getByRole('button', { name: 'Reconcile now', exact: true }).click()
  await expect(changes).toContainText('No movement statuses changed.')
  await page.getByRole('button', { name: 'Dismiss reconciliation changes', exact: true }).click()
  await expect(changes).toHaveCount(0)
})

